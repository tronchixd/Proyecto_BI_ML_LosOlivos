import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, precision_score

class AirQualityPredictor:
    def __init__(self):
        self.model = LogisticRegression()
        self.scaler = StandardScaler()

    def generate_synthetic_data(self, samples=300):
        np.random.seed(42)
        pm10 = np.random.uniform(10, 120, samples)
        co2 = np.random.uniform(350, 850, samples)
        temperatura = np.random.uniform(14, 30, samples)
        flujo_vehicular = np.random.randint(100, 3500, samples)

        prob_riesgo = (
            0.2 + (flujo_vehicular * 0.0002) + (co2 * 0.0005) + (pm10 * 0.003) - (temperatura * 0.01)
        )
        prob_riesgo = 1 / (1 + np.exp(-prob_riesgo))
        alto_riesgo = np.random.binomial(1, prob_riesgo)

        return pd.DataFrame({
            'pm10': pm10,
            'co2': co2,
            'temperatura': temperatura,
            'flujo_vehicular': flujo_vehicular,
            'alto_riesgo': alto_riesgo
        })

    def train(self, df):
        X = df[['pm10', 'co2', 'temperatura', 'flujo_vehicular']]
        y = df['alto_riesgo']

        X_scaled = self.scaler.fit_transform(X)
        X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

        self.model.fit(X_train, y_train)
        y_pred = self.model.predict(X_test)

        print(f"✅ Accuracy del Modelo: {accuracy_score(y_test, y_pred):.4f}")
        print(f"✅ Precisión del Modelo: {precision_score(y_test, y_pred):.4f}")

    def predict_new_sample(self, pm10, co2, temp, flujo):
        sample = np.array([[pm10, co2, temp, flujo]])
        sample_scaled = self.scaler.transform(sample)
        prob = self.model.predict_proba(sample_scaled)[0]
        return {"Probabilidad Seguro": round(float(prob[0]), 4), "Probabilidad Alto Riesgo": round(float(prob[1]), 4)}

if __name__ == "__main__":
    print("Iniciando entrenamiento del modelo de Los Olivos...\n")
